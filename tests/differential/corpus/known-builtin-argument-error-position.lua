print(pcall(function() local r = string.format("%d", {}) return r end))
print(pcall(function() local r = string.rep() return r end))
print(pcall(function() local r = math.floor({}) return r end))
print(pcall(function() return (string.char(256)) end))
print(pcall(function() return (string.gsub("abc", "(", "x")) end))
print(pcall(function() return (string.gsub("abc", "%", "x")) end))
print(pcall(function() return (string.gsub("abc", "b", "%2")) end))
print(pcall(function() return (string.rep("x", 1 << 62)) end))
print(pcall(function() return (string.format("%d", "x")) end))
print(pcall(function() return (string.format("%y", 1)) end))
print(pcall(function() return (string.format("%", 1)) end))
print(pcall(function() return (string.format("%d")) end))
print(pcall(function() return (string.unpack("i4", "ab")) end))
print(pcall(function() return (string.format("%d", 3.5)) end))
print(pcall(function() return (string.rep()) end))
print(pcall(function() return (("x").rep("x", {})) end))
